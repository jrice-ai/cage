#!/usr/bin/env python3
"""Turn ledger.csv into numbers.tex. Every number in the manuscript is a macro.

Usage: python3 gen_numbers.py [ledger.csv] [numbers.tex]
Keys must be letters only (LaTeX macro names). Values are written verbatim, with a
unary minus converted to a proper minus sign in math-safe form ($-$191.34 -> \num).
"""
import csv, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else "ledger.csv"
dst = sys.argv[2] if len(sys.argv) > 2 else "numbers.tex"

rows = list(csv.DictReader(open(src, newline="")))
bad = [r["key"] for r in rows if not re.fullmatch(r"[A-Za-z]+", r["key"])]
if bad:
    sys.exit(f"keys must be letters only: {bad}")
dupes = {k for k in [r["key"] for r in rows] if [r["key"] for r in rows].count(k) > 1}
if dupes:
    sys.exit(f"duplicate keys: {sorted(dupes)}")

def tex(v):
    v = v.strip()
    if re.fullmatch(r"-?\d[\d,]*(\.\d+)?", v):
        return v.replace("-", "\\ensuremath{-}", 1) if v.startswith("-") else v
    return v.replace("_", "\\_")

with open(dst, "w") as f:
    f.write("%% generated by gen_numbers.py from %s; do not edit\n" % src)
    for r in rows:
        f.write("\\newcommand{\\%s}{%s}%%%% %s | %s | %s\n" % (
            r["key"], tex(r["value"]), r.get("claim", ""), r.get("arm", ""), r.get("source", "")))
print(f"wrote {dst} with {len(rows)} macros")
