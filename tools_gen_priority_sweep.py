"""Priority sweep: Wrecker transitions held fixed, R/RD host-state priority mass varied.
Remaining mass is spread over K/KD/S/SD/U/UD in Wrecker's proportions (2:2:5:5:11:11)."""
M = [4, 16, 32, 48]                      # 64 is Wrecker itself
BASE = {'K': 2, 'KD': 2, 'S': 5, 'SD': 5, 'U': 11, 'UD': 11}   # sums to 36
TRANS = """    def state_transitions_probability(self):
        return {
            'K':  [0.30, 0.50, 0.20, None, None, None, None, None, None],
            'KD': [None, 0.50, 0.50, None, None, None, None, None, None],
            'S':  [0.10, None, None, 0.10, 0.80, None, None, None, None],
            'SD': [None, None, None, 0.20, 0.80, None, None, None, None],
            'U':  [0.10, None, None, None, None, 0.90, None, None, 0.0],
            'UD': [None, None, None, None, None, 1.00, None, None, 0.0],
            'R':  [0.05, None, None, None, None, None, 0.55, 0.40, 0.0],
            'RD': [None, None, None, None, None, None, 0.55, 0.45, 0.0],
        }
"""
for m in M:
    rest = 100 - m
    pri = {k: round(v * rest / 36) for k, v in BASE.items()}
    pri['K'] += rest - sum(pri.values())            # absorb rounding so the total is exactly 100
    pri['R'] = m // 2; pri['RD'] = m - m // 2
    assert sum(pri.values()) == 100, pri
    cls = f"FSRedAgentWreckerQ{m:02d}"
    body = f'''"""Priority sweep point: Wrecker transitions, R/RD priority mass = {m} of 100.
Generated by tools_gen_priority_sweep.py."""
from CybORG.Agents.SimpleAgents.FiniteStateRedAgent import FiniteStateRedAgent


class {cls}(FiniteStateRedAgent):

    def set_host_state_priority_list(self):
        return {pri}

''' + TRANS
    open(f"red_agents/{cls}.py", "w").write(body); print("wrote", cls, pri)
